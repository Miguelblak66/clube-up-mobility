#!/bin/bash
# scripts/create_local_db.sh
# Creates a local SQLite database (local.db) using schema.sql

set -euo pipefail

SCHEMA_FILE="schema.sql"
DB_FILE="local.db"

if ! command -v sqlite3 >/dev/null 2>&1; then
  echo "sqlite3 is required but not installed. Install sqlite3 and try again."
  exit 1
fi

if [ ! -f "$SCHEMA_FILE" ]; then
  echo "Cannot find $SCHEMA_FILE in the repository root. Run this script from the project root."
  exit 1
fi

if [ -f "$DB_FILE" ]; then
  echo "Overwriting existing $DB_FILE"
  rm -f "$DB_FILE"
fi

sqlite3 "$DB_FILE" < "$SCHEMA_FILE"

echo "Created $DB_FILE with schema from $SCHEMA_FILE"

echo "To create an admin user, use scripts/insert_admin.sh or run the SQL below in sqlite3:

-- Example (replace HASH and SALT generated by tools/hash_password.js):
-- INSERT INTO administradores (nome, email, senha, salt) VALUES ('Admin', 'admin@example.com', 'HASH', 'SALT');
"
